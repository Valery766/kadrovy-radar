TARGET = 153  # 150 остаются в каталоге, три закрываются наймом для демонстрации кабинета


# Средняя зарплата региона считается по всем профессиям и в столицах сильно завышена для рабочих
# специальностей: сжимаем разрыв между регионами, иначе учебный повар в Москве получает как инженер.
BASE_AVG = 80_000
REGION_COMPRESSION = 0.7


def salary(region_fns: str, share: float, schedule_k: float, exp_k: float, rnd: random.Random) -> int:
    avg = BASE_AVG * (REGIONS[region_fns]["avgSalary"] / BASE_AVG) ** REGION_COMPRESSION
    base = avg * share * schedule_k * exp_k * rnd.uniform(0.94, 1.07)
    return int(round(min(max(base, SALARY_MIN), SALARY_MAX) / 500.0) * 500)


CANDIDATE_ANSWERS = [
    ({"experience": "mid", "schedule": True, "expectedSalary": None}, 3),
    ({"experience": "senior", "schedule": True, "expectedSalary": None}, 3),
    ({"experience": "lt1", "schedule": True, "expectedSalary": None}, 2),
    ({"experience": "none", "schedule": False, "expectedSalary": None}, 0),
    ({"experience": "mid", "schedule": False, "expectedSalary": None}, 1),
]


def build_responses(rows: list[dict], rnd: random.Random) -> list[dict]:
    """Учебные отклики: кабинет работодателя на демонстрации не должен быть пустым.

    Кандидаты вымышлены и подписаны как учебные. Три вакансии закрываются наймом, чтобы
    было видно полный путь «отклик → приглашение → наём → закрытие».
    """
    picked = rows[:3] + rnd.sample(rows[3:], 9)
    plan = []
    for i, row in enumerate(picked):
        hired = i < 3
        count = 3 if hired else rnd.randint(1, 4)
        candidates = []
        for j in range(count):
            answers, score = CANDIDATE_ANSWERS[(i + j) % len(CANDIDATE_ANSWERS)]
            if hired:
                status = "hired" if j == 0 else "rejected"
            else:
                status = ["new", "new", "invited", "rejected"][j % 4]
            candidates.append({
                "name": f"Учебный кандидат {i * 4 + j + 1}",
                "answers": dict(answers, expectedSalary=(None if j % 2 else int(row["salary"] * 1.05 // 500 * 500))),
                "score": score,
                "status": status,
                "ageHours": rnd.randint(2, 20 * 24),
            })
        candidates.sort(key=lambda c: -c["ageHours"])
        plan.append({"vacancyKey": row["key"], "closedHoursAgo": rnd.randint(1, 24), "candidates": candidates})
    return plan


def main() -> None:
    rnd = random.Random(20260929)
    regions = list(CITY)
    rows, used = [], set()
    while len(rows) < TARGET:
        job = JOBS[len(rows) % len(JOBS)]
        profession_key, title, share, duties, conditions = job
        region_fns = regions[(len(rows) * 7 + len(rows) // len(JOBS)) % len(regions)]
        key = f"{profession_key}-{region_fns}-{len(rows)}"
        if key in used:
            continue
        used.add(key)
        group = GROUP_BY_PROFESSION[profession_key]
        schedule, schedule_k, _ = rnd.choice([s for s in SCHEDULES if s[2] is None or group in s[2]])
        experience, exp_k = rnd.choice(EXPERIENCE)
        employer = rnd.choice(EMPLOYERS[group])
        value = salary(region_fns, share, schedule_k, exp_k, rnd)
        city = CITY[region_fns]
        text = "\n".join([
            NOTICE,
            "",
            f"{title}. Город: {city}.",
            f"Зарплата: от {value:,} ₽ в месяц до вычета налогов.".replace(",", " "),
            f"График: {schedule}.",
            f"Опыт: {experience}.",
            f"Обязанности: {duties}.",
            f"Условия: {conditions}.",
            "",
            "Отклик отправляется внутри MAX: ответьте на три вопроса, и он попадёт в кабинет работодателя. Телефон и документы не нужны.",
        ])
        rows.append({
            "key": key,
            "title": title,
            "professionKey": profession_key,
            "regionFnsCode": region_fns,
            "regionCode": REGIONS[region_fns]["code"],
            "city": city,
            "employerName": f"{employer} (учебный пример)",
            "salary": value,
            "schedule": schedule,
            "experience": experience,
            "ageDays": rnd.randint(0, 20),
            "minutes": rnd.randrange(0, 24 * 60, 5),
            "text": text,
        })

    payload = {
        "batch": "demo-catalog-2026-09-29",
        "notice": NOTICE,
        "generator": "tools/build-demo-catalog.py",
        "vacancies": rows,
        "responses": build_responses(rows, rnd),
    }
    out = ROOT / "tools/demo-catalog.json"
    out.write_text(json.dumps(payload, ensure_ascii=False, indent=1) + "\n", "utf-8")
    regions_used = {r["regionFnsCode"] for r in rows}
    salaries = sorted(r["salary"] for r in rows)
    hired = sum(1 for r in payload["responses"] if any(c["status"] == "hired" for c in r["candidates"]))
    print(f"{out.relative_to(ROOT)}: {len(rows)} вакансий ({len(rows) - hired} останутся в каталоге), "
          f"{len(regions_used)} регионов, {len({r['professionKey'] for r in rows})} профессий, "
          f"зарплаты {salaries[0]:,}-{salaries[-1]:,} ₽, "
          f"откликов {sum(len(r['candidates']) for r in payload['responses'])} на {len(payload['responses'])} вакансиях".replace(",", " "))


if __name__ == "__main__":
    main()
